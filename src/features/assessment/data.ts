/** 영역마다 3문항(아직 안 본 문항 먼저) + 마지막 회상 문항 = 16문항 */
export function pickTest(seen: string[], today = new Date(), r: () => number = Math.random): Question[] {
  const bank = testBank(today);
  const picked = MODULE_IDS.flatMap((m) => {
    const all = bank.filter((q) => q.m === m).map((q) => [r(), q] as const).sort((a, b) => a[0] - b[0]).map(([, q]) => q);
    return [...all.filter((q) => !seen.includes(q.id)), ...all.filter((q) => seen.includes(q.id))].slice(0, PER_AREA);
  });
  return [...picked, RECALL_QUESTION];
}

